"""
params.py -- constants, plant parameters, configuration loading and the model/true plant pair.

Inverse-crime rule: the Gatekeeper may only ever see the NOMINAL parameters (configs/gatekeeper.yaml).
The TRUE plant is generated by make_plant_pair(mismatch, seed) and is never written to a config file.
"""
from __future__ import annotations

from dataclasses import asdict, dataclass, field, fields, replace
from pathlib import Path
from typing import Dict, Optional, Tuple

import numpy as np
import yaml

CONFIG_DIR = Path(__file__).resolve().parents[2] / "configs"

