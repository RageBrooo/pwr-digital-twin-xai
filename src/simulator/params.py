SENSOR_FAULTS = ["sensor_drift", "sensor_bias", "sensor_stuck"]
CLASSES = ["normal"] + HARDWARE_FAULTS + SENSOR_FAULTS


@dataclass(frozen=True)
class PlantParams:
    # neutronics
    Lambda: float = 2.0e-5
    alpha_D: float = -2.5e-5
    alpha_M: float = -2.0e-4
    k_void: float = 0.05
    # thermal-hydraulics
    P0: float = 3.0e9
    W0: float = 17500.0
    cp: float = 5600.0
    Cf: float = 4.5e7
    Cc0: float = 5.6e8
    hA: float = 8.8e6
    sg_eff: float = 0.8
    T_sec: float = 283.5
    tau_pump: float = 3.0
    # inventory
    beta_exp: float = 1.0e-3
    k_charge: float = 0.02
    charge_max: float = 5.0e-5
    # instrumentation calibration (nominal = perfect)
    flux_cal_1: float = 1.0
    flux_cal_2: float = 1.0
    flow_cal: float = 1.0
    level_off_1: float = 0.0
    level_off_2: float = 0.0

    def to_dict(self) -> Dict[str, float]:
        return asdict(self)

    @classmethod
    def from_dict(cls, d: Dict[str, float]) -> "PlantParams":
        names = {f.name for f in fields(cls)}
        return cls(**{k: float(v) for k, v in d.items() if k in names})

    @classmethod
    def nominal(cls, path: Optional[Path] = None) -> "PlantParams":
        """the Gatekeeper's assumed parameters (configs/gatekeeper.yaml)"""
        with open(path or CONFIG_DIR / "gatekeeper.yaml") as f:
            return cls.from_dict(yaml.safe_load(f))


@dataclass(frozen=True)
class SensorConfig:
    sigma: Dict[str, float] = field(default_factory=lambda: {
        "flux_1": 0.002, "flux_2": 0.002, "T_in": 0.10, "T_out_1": 0.10, "T_out_2": 0.10,
        "T_fuel": 1.0, "flow": 0.004, "pump_speed": 0.002, "level_1": 0.001, "level_2": 0.001})
    noise_scale: float = 1.0
    tau_T: float = 0.0


@dataclass(frozen=True)
class SimConfig:
    dt: float = 0.1
    ctrl_dt: float = 1.0
    method: str = "Radau"
    rtol: float = 1e-6
    atol: float = 1e-9
    Kp: float = 0.002
    Ki: float = 0.0004
    tau_ff: float = 6.0
    ctrl_flux_mode: str = "mean"


@dataclass(frozen=True)
class MismatchConfig:
    fields: Dict[str, float] = field(default_factory=lambda: {
        "Cf": 1.0, "Cc0": 1.0, "hA": 1.0, "cp": 0.6, "W0": 0.8, "beta_exp": 1.0, "flow_cal": 0.6})
    flux_common_weight: float = 1.0
    flux_channel_fraction: float = 0.25
    level_offset_weight: float = 0.1


def load_sim_config(path: Optional[Path] = None) -> Tuple[SimConfig, SensorConfig, MismatchConfig]:
    with open(path or CONFIG_DIR / "simulator.yaml") as f:
        y = yaml.safe_load(f)
    return SimConfig(**y["sim"]), SensorConfig(**y["sensors"]), MismatchConfig(**y["mismatch"])


def make_plant_pair(mismatch: float = 0.03, seed: int = 0, mcfg: Optional[MismatchConfig] = None,
                    nominal: Optional[PlantParams] = None) -> Tuple[PlantParams, PlantParams]:
    """Return (model_params, true_params). `mismatch` is the maximum relative offset (0.05 = 5 %)."""
    mcfg = mcfg or MismatchConfig()
    model = nominal or PlantParams()
    rng = np.random.default_rng(seed + 10_007)
    kw = {}
    for f, wgt in mcfg.fields.items():
        kw[f] = getattr(model, f) * (1 + mismatch * wgt * rng.choice([-1, 1]) * rng.uniform(0.5, 1.0))
    common = mismatch * mcfg.flux_common_weight * rng.choice([-1, 1]) * rng.uniform(0.9, 1.0)
    for f in ("flux_cal_1", "flux_cal_2"):
        kw[f] = 1 + common + mcfg.flux_channel_fraction * mismatch * rng.uniform(-1, 1)
    for f in ("level_off_1", "level_off_2"):                       # drawn last: keeps earlier draws stable
        kw[f] = mcfg.level_offset_weight * mismatch * rng.uniform(-1, 1)
    return model, replace(model, **kw)


def mismatch_offsets(model: PlantParams, true: PlantParams) -> Dict[str, float]:
    """relative offset (true/model - 1) for scaled parameters, absolute offset for the additive ones"""
    out = {}
    for f in fields(PlantParams):
        m, t = getattr(model, f.name), getattr(true, f.name)
        if t != m:
            out[f.name] = (t - m) if f.name.startswith("level_off") else (t / m - 1.0)
    return out


def equilibrium(p: PlantParams, n: float, w: float = 1.0, d: float = 0.0, m: float = 1.0) -> Dict[str, float]:
    """steady state of the thermal loop at relative power n (used for initialisation and the gatekeeper)"""
    W = p.W0 * w * (1 - d) * flow_penalty(m)
    G = 2 * p.sg_eff * W * p.cp / (2 - p.sg_eff)          # SG conductance seen by the coolant node
    Tc = p.T_sec + p.P0 * n / G
    Tin = (2 * (1 - p.sg_eff) * Tc + p.sg_eff * p.T_sec) / (2 - p.sg_eff)
    return dict(Tc=Tc, Tin=Tin, Tout=2 * Tc - Tin, Tf=Tc + p.P0 * n / p.hA, W=W)


def flow_penalty(m):
    """loss-of-suction penalty on flow when inventory is low (scalar or array)"""
    return 1.0 - 1.5 * np.maximum(0.0, 0.95 - m)
